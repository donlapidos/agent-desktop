  islandAction: (action) => ipcRenderer.send("island-action", action),
  onMarksClear: on("marks-clear"),
  onMarkDrawn: on("mark-drawn"),
  onMarks: on("marks"),
  onMarkStart: on("mark-start"),
  onMarkCommand: on("mark-command"),
